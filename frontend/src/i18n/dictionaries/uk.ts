/** Ukrainian has three count forms: 1 витрата, 2 витрати, 5 витрат. */
function count(n: number, one: string, few: string, many: string) {
  const form = plural.select(n);
  return `${n} ${form === "one" ? one : form === "few" ? few : many}`;
}

